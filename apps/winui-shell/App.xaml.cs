    private static object CompatFallbackResourceFromToken(string token, ResourceDictionary resources)
    {
        static double ParseComponent(string value)
            => string.IsNullOrEmpty(value) || value == "-"
                ? 0d
                : double.Parse(value, System.Globalization.CultureInfo.InvariantCulture);

        switch (token[0])
        {
            case 'C':
            {
                switch (token)
                {
                    case "C:Transparent":
                        return new Microsoft.UI.Xaml.Media.SolidColorBrush(Microsoft.UI.Colors.Transparent);
                    case "C:Black":
                        return new Microsoft.UI.Xaml.Media.SolidColorBrush(Microsoft.UI.Colors.Black);
                    case "C:White":
                        return new Microsoft.UI.Xaml.Media.SolidColorBrush(Microsoft.UI.Colors.White);
                    case "C:LightGray":
                        return new Microsoft.UI.Xaml.Media.SolidColorBrush(Microsoft.UI.Colors.LightGray);
                }

                if (token.StartsWith("C:{ThemeResource ", StringComparison.Ordinal))
                {
                    var resourceKey = token.Substring("C:{ThemeResource ".Length).TrimEnd('}');
                    if (CompatTryResolveThemeColor(resources, resourceKey, out var resolved))
                    {
                        return new Microsoft.UI.Xaml.Media.SolidColorBrush(resolved);
                    }

                    return new Microsoft.UI.Xaml.Media.SolidColorBrush(
                        Windows.UI.Color.FromArgb(0xFF, 0x76, 0x76, 0x76));
                }

                var hex = token.Substring(3);
                var alpha = (byte)Convert.ToUInt32(hex.Substring(0, 2), 16);
                var red = (byte)Convert.ToUInt32(hex.Substring(2, 2), 16);
                var green = (byte)Convert.ToUInt32(hex.Substring(4, 2), 16);
                var blue = (byte)Convert.ToUInt32(hex.Substring(6, 2), 16);
                return new Microsoft.UI.Xaml.Media.SolidColorBrush(Windows.UI.Color.FromArgb(alpha, red, green, blue));
            }
            case 'T':
            {
                var parts = token.Substring(2).Split(',');
                return new Thickness(ParseComponent(parts[0]), ParseComponent(parts[1]), ParseComponent(parts[2]), ParseComponent(parts[3]));
            }
            case 'R':
            {
                var parts = token.Substring(2).Split(',');
                return new CornerRadius(ParseComponent(parts[0]), ParseComponent(parts[1]), ParseComponent(parts[2]), ParseComponent(parts[3]));
            }
            case 'D':
                return ParseComponent(token.Substring(2));
            case 'F':
                return new Microsoft.UI.Xaml.Media.FontFamily(token.Substring(2));
            case 'S':
                return token.Substring(2);
            case 'B':
                return bool.Parse(token.Substring(2));
            case 'G':
                return new Microsoft.UI.Xaml.GridLength(
                    double.Parse(token.Substring(2), System.Globalization.CultureInfo.InvariantCulture),
                    Microsoft.UI.Xaml.GridUnitType.Pixel);
            case 'W':
            {
                var weightValue = token.Substring(2).Trim() switch
                {
                    "Thin" => 100, "ExtraLight" => 200, "Light" => 300, "SemiLight" => 350,
                    "Normal" => 400, "Medium" => 500, "SemiBold" => 600, "Bold" => 700,
                    "ExtraBold" => 800, "Black" => 900,
                    _ => 400,
                };
                return new Windows.UI.Text.FontWeight { Weight = (ushort)weightValue };
            }
            case 'V':
                return (Microsoft.UI.Xaml.Visibility)Enum.Parse(
                    typeof(Microsoft.UI.Xaml.Visibility), token.Substring(2), false);
            case 'H':
                return (Microsoft.UI.Xaml.HorizontalAlignment)Enum.Parse(
                    typeof(Microsoft.UI.Xaml.HorizontalAlignment), token.Substring(2), false);
            case 'A':
                return (Microsoft.UI.Xaml.VerticalAlignment)Enum.Parse(
                    typeof(Microsoft.UI.Xaml.VerticalAlignment), token.Substring(2), false);
            case 'Y':
            {
                var targetName = token.Substring(2);
                string candidateNamespace;
                string typeName;
                if (targetName.StartsWith("controls:", StringComparison.Ordinal))
                {
                    candidateNamespace = "Microsoft.UI.Xaml.Controls";
                    typeName = targetName.Substring("controls:".Length);
                }
                else if (targetName.StartsWith("primitives:", StringComparison.Ordinal))
                {
                    candidateNamespace = "Microsoft.UI.Xaml.Controls.Primitives";
                    typeName = targetName.Substring("primitives:".Length);
                }
                else if (targetName is "Rectangle" or "Shape")
                {
                    candidateNamespace = "Microsoft.UI.Xaml.Shapes";
                    typeName = targetName;
                }
                else if (targetName is "ButtonBase" or "RepeatButton" or "ToggleButton" or "ScrollBar" or "Thumb"
                    or "LoopingSelector" or "LoopingSelectorItem" or "PivotHeaderItem")
                {
                    candidateNamespace = "Microsoft.UI.Xaml.Controls.Primitives";
                    typeName = targetName;
                }
                else if (targetName is "FrameworkElement")
                {
                    candidateNamespace = "Microsoft.UI.Xaml";
                    typeName = targetName;
                }
                else
                {
                    candidateNamespace = "Microsoft.UI.Xaml.Controls";
                    typeName = targetName;
                }

                var resolvedType = typeof(Microsoft.UI.Xaml.Controls.Control).Assembly.GetType(
                    candidateNamespace + "." + typeName);
                if (resolvedType is null)
                {
                    throw new InvalidOperationException("Unknown compat style target type: " + targetName);
                }

                return new Microsoft.UI.Xaml.Style(resolvedType);
            }
            case 'E':
            {
                var enumParts = token.Substring(2).Split(':');
                return enumParts[0] switch
                {
                    "TextTrimming" => Enum.Parse(typeof(Microsoft.UI.Xaml.TextTrimming), enumParts[1]),
                    "Symbol" => Enum.Parse(typeof(Microsoft.UI.Xaml.Controls.Symbol), enumParts[1]),
                    "BackgroundSizing" => Enum.Parse(typeof(Microsoft.UI.Xaml.Controls.BackgroundSizing), enumParts[1]),
                    "ListViewItemPresenterCheckMode" => Enum.Parse(
                        typeof(Microsoft.UI.Xaml.Controls.Primitives.ListViewItemPresenterCheckMode), enumParts[1]),
                    _ => throw new InvalidOperationException("Unknown compat enum resource: " + enumParts[0]),
                };
            }
            default:
                throw new InvalidOperationException("Unknown compat theme fallback token: " + token);
        }
    }

    private static bool CompatTryResolveThemeColor(ResourceDictionary resources, string key, out Windows.UI.Color color)
    {
        static bool FromValue(object value, out Windows.UI.Color parsed)
        {
            switch (value)
            {
                case Windows.UI.Color exactColor:
                    parsed = exactColor;
                    return true;
                case Microsoft.UI.Xaml.Media.SolidColorBrush brush:
                    parsed = brush.Color;
                    return true;
                default:
                    parsed = default;
                    return false;
            }
        }

        foreach (var themeKey in new[] { "Light", "Default" })
        {
            if (resources.ThemeDictionaries.TryGetValue(themeKey, out var themeValue)
                && themeValue is ResourceDictionary themeDictionary
                && themeDictionary.TryGetValue(key, out var themeResource)
                && FromValue(themeResource, out color))
            {
                return true;
            }
        }

        if (resources.TryGetValue(key, out var appResource)
            && FromValue(appResource, out color))
        {
            return true;
        }

        if (key.StartsWith("SystemAccentColor", StringComparison.Ordinal))
        {
            try
            {
                var uiSettings = new Windows.UI.ViewManagement.UISettings();
                var accentKey = key switch
                {
                    "SystemAccentColor" => Windows.UI.ViewManagement.UIColorType.Accent,
                    "SystemAccentColorDark1" => Windows.UI.ViewManagement.UIColorType.AccentDark1,
                    "SystemAccentColorDark2" => Windows.UI.ViewManagement.UIColorType.AccentDark2,
                    "SystemAccentColorDark3" => Windows.UI.ViewManagement.UIColorType.AccentDark3,
                    "SystemAccentColorLight1" => Windows.UI.ViewManagement.UIColorType.AccentLight1,
                    "SystemAccentColorLight2" => Windows.UI.ViewManagement.UIColorType.AccentLight2,
                    "SystemAccentColorLight3" => Windows.UI.ViewManagement.UIColorType.AccentLight3,
                    _ => default(Windows.UI.ViewManagement.UIColorType?),
                };
                if (accentKey is { } colorType)
                {
                    color = uiSettings.GetColorValue(colorType);
                    return true;
                }
            }
            catch (Exception)
            {
                // Fall through to the neutral color below.
            }
        }

        color = default;
        return false;
    }

