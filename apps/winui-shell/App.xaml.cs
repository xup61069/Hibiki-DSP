    internal static void CompatAppendLog(string message)
    {
        try
        {
            var directory = System.IO.Path.Combine(
                Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
                "Hibiki DSP");
            System.IO.Directory.CreateDirectory(directory);
            System.IO.File.AppendAllText(
                System.IO.Path.Combine(directory, "compat-launch-unhandled-v1.log"),
                DateTimeOffset.Now.ToString("O") + " " + message +
                System.Environment.NewLine);
        }
        catch (Exception)
        {
            // Diagnostics must never take the preview down on their own.
        }
    }

